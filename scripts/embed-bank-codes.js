#!/usr/bin/env node
// Embeds the vendored bank-code table in the SDK as a string constant.
//
// A string rather than a JSON import: the build copies a `.json` file into `lib` as-is, and Metro
// turns a JSON import into an object literal that is built when the importing module loads — at SDK
// import, whether or not the app ever names a bank by code. A string costs nothing until
// `JSON.parse` runs on first use.
//
// After re-vendoring test/fixtures/bank-codes.json, run `node scripts/embed-bank-codes.js`.
// bankCodes.test.ts fails when the constant and the vendored file differ by a single byte.
import { Buffer } from 'node:buffer';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = 'test/fixtures/bank-codes.json';
const TARGET = 'src/query/bankCodesJson.ts';

const json = readFileSync(join(ROOT, SOURCE), 'utf8');

// A template literal ends at a backtick, interpolates at `${` and unescapes at a backslash, so any
// of them would change the embedded bytes.
if (/[`\\]|\$\{/.test(json)) {
  console.error(`embed-bank-codes: ${SOURCE} contains a character that a template literal alters.`);
  process.exit(1);
}
JSON.parse(json);

const source = [
  `// Generated by scripts/embed-bank-codes.js from ${SOURCE}.`,
  '// Do not edit: re-vendor that file and re-run the script. bankCodes.test.ts fails if the two differ.',
  // Annotated `string` so the declaration file says `string` instead of repeating the whole table
  // as a literal type.
  `export const BANK_CODES_JSON: string = \`${json}\`;`,
  '',
].join('\n');

writeFileSync(join(ROOT, TARGET), source);
console.log(`embed-bank-codes: wrote ${TARGET} (${Buffer.byteLength(json)} bytes of JSON)`);
